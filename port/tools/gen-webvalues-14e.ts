// gen-webvalues-14e.ts: writes Tests/Logic/WebValues14e.swift from the web's
// own code, so the phone's feed fingerprints and its reading of the server's
// /api/import/ics answer are pinned to what the web actually produces.
//
// Run (node 22+, TZ=UTC like CI) from a folder holding copies of the web's
// lib/ics-import.ts, ics-reconcile.ts, merge.ts, deadline.ts and plan.ts with
// ".ts" added to their relative imports (see p14b's copylib.py):
//   TZ=UTC node --experimental-strip-types gen-webvalues-14e.ts > WebValues14e.swift
import { classFingerprint, taskFingerprint } from "./ics-reconcile.ts";
import { parseIcs } from "./ics-import.ts";

// A Swift string literal: backslash, quote, newline, return and tab escaped
// as Swift writes them, other control characters as \u{…}, the rest as is.
const swiftString = (s: string) =>
  '"' +
  [...s]
    .map((ch) => {
      if (ch === "\\") return "\\\\";
      if (ch === '"') return '\\"';
      if (ch === "\n") return "\\n";
      if (ch === "\r") return "\\r";
      if (ch === "\t") return "\\t";
      const code = ch.codePointAt(0) ?? 0;
      return code < 0x20 ? `\\u{${code.toString(16)}}` : ch;
    })
    .join("") +
  '"';
const lines: string[] = [];
lines.push("// WebValues14e.swift: generated by port/tools/gen-webvalues-14e.ts from the");
lines.push("// web's own lib/ics-reconcile.ts and lib/ics-import.ts (node, TZ=UTC).");
lines.push("// Do not edit by hand. Kelvin does not type this file.");
lines.push("@testable import CPLogic");
lines.push("");

type C = { name: string; days: number[]; start: number; end: number; room?: string };
const classes: C[] = [
  { name: "Physics 101", days: [0, 2], start: 540, end: 600 },
  { name: "Physics 101", days: [2, 0], start: 540, end: 600, room: "" },
  { name: "Bio \"Lab\" / Section\\2", days: [4], start: 0, end: 59, room: "Hall A/2" },
  { name: "Café ☕️ Ünïcode", days: [6, 5, 1], start: 1380, end: 1439, room: "Room\t3\nEast" },
  { name: "Ctrl\u0001\u001f\b\f\r", days: [], start: 600, end: 660, room: "R" },
];
lines.push("/// web: classFingerprint for each class, in this order.");
lines.push("let WEB_CLASS_FINGERPRINTS: [(name: String, days: [Int], start: Int, end: Int, room: String?, hash: String)] = [");
for (const c of classes) {
  const room = c.room === undefined ? "nil" : swiftString(c.room);
  lines.push(`    (name: ${swiftString(c.name)}, days: [${c.days.join(", ")}], start: ${c.start}, end: ${c.end}, room: ${room}, hash: "${classFingerprint(c as any)}"),`);
}
lines.push("]");
lines.push("");

type T = { title: string; due: string | null; dueTime: string | null; kind: string };
const tasks: T[] = [
  { title: "Lab report 3", due: "2026-10-01", dueTime: "23:59", kind: "assignment" },
  { title: "Midterm", due: "2026-10-15", dueTime: null, kind: "exam" },
  { title: "Read \"ch. 4\" \\ notes", due: null, dueTime: null, kind: "assignment" },
  { title: "Ünïcode 📚 essay", due: "2026-12-01", dueTime: "08:05", kind: "quiz" },
];
lines.push("/// web: taskFingerprint for each assignment, in this order.");
lines.push("let WEB_TASK_FINGERPRINTS: [(title: String, due: String?, dueTime: String?, kind: String, hash: String)] = [");
for (const t of tasks) {
  const due = t.due === null ? "nil" : swiftString(t.due);
  const time = t.dueTime === null ? "nil" : swiftString(t.dueTime);
  lines.push(`    (title: ${swiftString(t.title)}, due: ${due}, dueTime: ${time}, kind: ${swiftString(t.kind)}, hash: "${taskFingerprint(t as any)}"),`);
}
lines.push("]");
lines.push("");

// A feed as a school publishes it: two weekly classes (one with a room and
// UNTIL), a timed deadline, an all-day exam, a cancelled event and one in
// the past. The server answers /api/import/ics with parseIcs's result as JSON.
const ics = [
  "BEGIN:VCALENDAR", "VERSION:2.0",
  "BEGIN:VEVENT", "UID:cls-bio@school", "SUMMARY:Biology 110", "DTSTART:20260901T091500",
  "DTEND:20260901T103000", "RRULE:FREQ=WEEKLY;BYDAY=TU,TH;UNTIL=20261211T235900Z",
  "LOCATION:Science Hall 204", "END:VEVENT",
  "BEGIN:VEVENT", "UID:cls-hist@school", "SUMMARY:World History", "DTSTART:20260902T130000",
  "DTEND:20260902T141500", "RRULE:FREQ=WEEKLY;BYDAY=MO,WE,FR", "END:VEVENT",
  "BEGIN:VEVENT", "UID:task-essay@school", "SUMMARY:Essay 2 \\, final draft", "DTSTART:20261030T235900", "END:VEVENT",
  "BEGIN:VEVENT", "UID:task-mid@school", "SUMMARY:Midterm exam", "DTSTART;VALUE=DATE:20261021", "END:VEVENT",
  "BEGIN:VEVENT", "UID:task-off@school", "SUMMARY:Field trip", "STATUS:CANCELLED", "DTSTART:20261105T090000", "END:VEVENT",
  "BEGIN:VEVENT", "UID:task-old@school", "SUMMARY:Old quiz", "DTSTART:20250105T090000", "END:VEVENT",
  "END:VCALENDAR",
].join("\r\n");
const now = new Date(2026, 9, 1, 12, 0); // 2026-10-01 12:00 local
const result = parseIcs(ics, now);
lines.push("/// The calendar text the server read for `WEB_FEED_SERVER_JSON`.");
lines.push(`let WEB_FEED_ICS = ${swiftString(ics)}`);
lines.push("");
lines.push("/// The moment the server read it: 2026-10-01 12:00, in the zone the tests run in.");
lines.push(`let WEB_FEED_NOW_PARTS = (year: 2026, month: 10, day: 1, hour: 12, minute: 0)`);
lines.push("");
lines.push("/// web: the JSON /api/import/ics answers with for that feed (`NextResponse.json(parseIcs(text))`).");
lines.push(`let WEB_FEED_SERVER_JSON = ${swiftString(JSON.stringify(result))}`);
console.log(lines.join("\n"));
